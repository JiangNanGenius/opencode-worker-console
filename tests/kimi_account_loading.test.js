'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../web/manage.js'),'utf8');
const controller=source.slice(source.indexOf('let kimiAccountLoginTimer='),source.indexOf('function showKimiAccountLogin('));
test('account refresh preserves prior quota, coalesces pending reads and recovers after success or failure',async()=>{
 const elements={'kimi-account-state':{textContent:'last successful sample'},'kimi-account-refresh':{disabled:false},'kimi-account-windows':{innerHTML:'previous total quota'}};
 let calls=0,resolve,reject;
 const context={Promise,$:id=>elements[id],tr:key=>key,request:()=>{calls++;return new Promise((yes,no)=>{resolve=yes;reject=no;});}};
 vm.createContext(context);vm.runInContext(controller,context);
 context.renderKimiAccount=value=>{elements['kimi-account-state'].textContent='connected';elements['kimi-account-windows'].innerHTML=value.total;};
 const first=context.loadKimiAccount(),duplicate=context.loadKimiAccount();
 assert.equal(elements['kimi-account-state'].textContent,'kimiAccount.loading');
 assert.equal(elements['kimi-account-refresh'].disabled,true);
 assert.equal(elements['kimi-account-windows'].innerHTML,'previous total quota');
 await Promise.resolve();assert.equal(calls,1);
 resolve({total:'fresh total quota'});await Promise.all([first,duplicate]);
 assert.equal(elements['kimi-account-state'].textContent,'connected');
 assert.equal(elements['kimi-account-windows'].innerHTML,'fresh total quota');
 assert.equal(elements['kimi-account-refresh'].disabled,false);
 const failed=context.loadKimiAccount();await Promise.resolve();assert.equal(calls,2);
 reject(new Error('timed out'));await failed;
 assert.match(elements['kimi-account-state'].textContent,/kimiAccount.unavailable · timed out/);
 assert.equal(elements['kimi-account-windows'].innerHTML,'fresh total quota');
 assert.equal(elements['kimi-account-refresh'].disabled,false);
 const retry=context.loadKimiAccount();await Promise.resolve();assert.equal(calls,3);resolve({total:'recovered quota'});await retry;
 assert.equal(elements['kimi-account-windows'].innerHTML,'recovered quota');
});
